#!/usr/bin/env python3
"""Regenerates tests/zipdata.h: small real-world-shaped .zip archives (made by Python's zipfile, i.e. by zlib, not by
the code under test) used by tests/test_plat.c. Usage: python3 tests/gen_zipdata.py > tests/zipdata.h
The contents are re-derived in the C test (same LCG, same names), so the two have to stay in sync."""
import io, zipfile, sys

U_MUSICA, U_CHECK, U_JP, U_NTILDE = "Música", "✓", "音楽", "ñ"
OSU = ("osu file format v14\r\n\r\n[General]\r\nAudioFilename: audio " + U_JP + ".mp3\r\nPreviewTime: 1000\r\n\r\n"
       "[Metadata]\r\nTitle:T" + U_MUSICA + "\r\nArtist:Artist\r\nCreator:me\r\nVersion:Easy\r\n\r\n"
       "[Difficulty]\r\nHPDrainRate:5\r\nCircleSize:4\r\nOverallDifficulty:5\r\nApproachRate:5\r\nSliderMultiplier:1.4\r\n\r\n"
       "[TimingPoints]\r\n0,500,4,1,0,100,1,0\r\n\r\n"
       "[HitObjects]\r\n100,100,1000,1,0\r\n200,150,1500,1,0\r\n300,200,2000,1,0\r\n")

def lcg(n, seed):                       # same generator as lcg_bytes() in the C test
    out, x = bytearray(), seed
    for _ in range(n):
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        out.append(ord('a') + (x >> 16) % 12)
    return bytes(out)

def build(entries, default=zipfile.ZIP_DEFLATED):
    b = io.BytesIO()
    with zipfile.ZipFile(b, "w") as z:
        for name, data, method in entries:
            zi = zipfile.ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))
            zi.compress_type = method if method is not None else default
            zi.external_attr = (0o40755 << 16) if name.endswith("/") else (0o100644 << 16)
            z.writestr(zi, data, compresslevel=9 if zi.compress_type == zipfile.ZIP_DEFLATED else None)
    return b.getvalue()

D, S = zipfile.ZIP_DEFLATED, zipfile.ZIP_STORED
osz = build([
    ("Artist - T" + U_MUSICA + " [Easy].osu", OSU.encode(), D),          # text: dynamic huffman
    ("audio " + U_JP + ".mp3", lcg(6000, 1), D),                           # 6000 bytes: long matches, dynamic huffman
    ("sub/", b"", S),                                                      # explicit directory entry
    ("sub/inner " + U_NTILDE + ".txt", b"hi", D),                          # tiny: fixed huffman
    ("sub/dir " + U_CHECK + "/deep.txt", b"deep", S),                      # stored, parent dir without its own entry
    ("Back\\slash.txt", b"bs", D),                                         # Windows-style separator
])
osk = build([
    ("skin.ini", b"[General]\nName: D\n", D),
    ("Hitcircle.PNG", lcg(3000, 7), D),
    ("Fonts\\Hit\\score-0.png", b"d" * 50 + b"e" * 50, D),
])
# a repeat 25000 bytes back: the longest distance codes (24577..32768, 13 extra bits)
far = build([("far.bin", lcg(3000, 3) + bytes(22000) + lcg(3000, 3), D)])
bz = build([("bz.txt", b"bzip2 " * 40, zipfile.ZIP_BZIP2)])               # method 12: not handled by the built-in reader

def emit(name, data):
    print("static const unsigned char %s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 16):
        print("    " + ",".join("0x%02x" % c for c in data[i:i + 16]) + ",")
    print("};")

print("/* generated by tests/gen_zipdata.py, do not edit */")
emit("ZIP_OSZ", osz); emit("ZIP_OSK", osk); emit("ZIP_FAR", far); emit("ZIP_BZ", bz)
